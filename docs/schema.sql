COMMENT ON COLUMN audit_logs.actor_id IS '행위자 (FK: users.id, 계정 미상이면 NULL)';
COMMENT ON COLUMN audit_logs.actor_email IS '행위 시점 이메일 스냅샷 (로그인 실패는 입력값 그대로)';
COMMENT ON COLUMN audit_logs.actor_name IS '행위 시점 이름 스냅샷';
COMMENT ON COLUMN audit_logs.actor_ip IS '요청 IP (IPv6까지)';
COMMENT ON COLUMN audit_logs.target_type IS '대상 종류 (AuditTarget)';
